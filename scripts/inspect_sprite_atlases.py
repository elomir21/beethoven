"""Read alpha bounds without changing images; generate the runtime atlas layout."""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parents[1]
layouts = {}
for name, columns, rows in [('characters/beethoven/beethoven-hd.png', 4, 3), ('characters/rivals/rivals-hd.png', 4, 4), ('characters/cats/cats-hd.png', 4, 2), ('characters/family/family-hd.png', 6, 2), ('characters/beethoven/beethoven-vasco-hd.png', 4, 3), ('characters/bosses/rat-hd.png', 2, 2)]:
    image = Image.open(root / 'public/assets' / name).convert('RGBA')
    alpha = image.getchannel('A').point(lambda a: 255 if a >= 32 else 0)
    frames = []
    for row in range(rows):
        for column in range(columns):
            left, top = round(column * image.width / columns), round(row * image.height / rows)
            right, bottom = round((column + 1) * image.width / columns), round((row + 1) * image.height / rows)
            bounds = alpha.crop((left, top, right, bottom)).getbbox()
            if bounds is None:
                raise ValueError(f'Empty frame: {name} {row}:{column}')
            x1, y1, x2, y2 = bounds
            frames.append({'x': left + x1, 'y': top + y1, 'w': x2 - x1, 'h': y2 - y1})
    layouts[name] = {'width': image.width, 'height': image.height, 'frames': frames}
output = root / 'src/data/spriteFrames.js'
output.write_text('// Generated by scripts/inspect_sprite_atlases.py; source images are preserved.\nexport const spriteFrames=' + json.dumps(layouts, separators=(',', ':')) + ';\n')
print(f'{len(layouts)} atlas layouts written to {output.relative_to(root)}')
